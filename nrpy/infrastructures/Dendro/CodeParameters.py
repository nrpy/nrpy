# nrpy/infrastructures/Dendro/CodeParameters.py
"""
Emit the generated parameter header and sample parameter file for a Dendro solver.

Every name, type and default is read from the NRPy CodeParameter registry, as
BHaH's ``CodeParameters.py`` does.  Only parameters that a registered CFunction
actually uses are emitted, so the generated struct matches the closure the
solver needs; no physics parameter table is authored here and no equation module
is imported.

Author: Zachariah B. Etienne
        zachetie **at** gmail **dot* com
"""

from typing import Any, List, Optional

import nrpy.params as par

BANNER = (
    "// GENERATED FILE - DO NOT EDIT\n"
    "// AUTOMATICALLY GENERATED BY nrpy.infrastructures.Dendro.CodeParameters\n"
)


def array_size(cparam_type: str) -> Optional[str]:
    """
    Return the array length of a registered CodeParameter type, or ``None``.

    :param cparam_type: Registered ``cparam_type`` string.
    :return: The declared length as a string, or ``None`` for a scalar.
    :raises ValueError: If the declared length is not a decimal literal.

    Doctests:
    >>> array_size("REAL")
    >>> array_size("char[100]")
    '100'
    """
    if "[" not in cparam_type:
        return None
    size = cparam_type.split("[", 1)[1].split("]", 1)[0].strip()
    if not size.isdigit():
        raise ValueError(f"Invalid array size {size!r} in {cparam_type!r}.")
    return size


def c_type(cparam_type: str, scalar_type: str) -> str:
    """
    Map a registered CodeParameter type to its generated C++ base type.

    ``REAL`` maps to the registered Dendro scalar alias; ``float``, ``double``,
    ``int``, ``bool`` and ``char`` map to the same spelled built-in types.  For
    an array type the base is mapped and the length is carried separately, as
    BHaH's ``BHaH_defines_h`` does, because a C array declares its length after
    the member name.

    :param cparam_type: Registered ``cparam_type`` string.
    :param scalar_type: Registered Dendro scalar alias (e.g. ``DendroScalar``).
    :return: The generated C++ base-type spelling.
    :raises ValueError: If the type has no mapping.

    Doctests:
    >>> c_type("REAL", "DendroScalar")
    'DendroScalar'
    >>> c_type("char[100]", "DendroScalar")
    'char'
    """
    base = cparam_type.split("[", 1)[0].strip()
    if base in ("REAL", "DendroScalar"):
        return scalar_type
    if base in ("float", "double", "int", "bool", "char"):
        return base
    if base == "#define":
        raise ValueError(
            "`#define` CodeParameters are compile-time constants and are never "
            "`GeneratedParams` members."
        )
    raise ValueError(f"CodeParameter type {cparam_type!r} has no generated mapping.")


def member_declaration(cp_name: str, cparam_type: str, scalar_type: str) -> str:
    """
    Render one ``GeneratedParams`` member declaration.

    :param cp_name: Registered CodeParameter name.
    :param cparam_type: Registered ``cparam_type`` string.
    :param scalar_type: Registered Dendro scalar alias.
    :return: The C++ member declaration, without indentation.

    Doctests:
    >>> member_declaration("eta", "REAL", "DendroScalar")
    'DendroScalar eta;'
    >>> member_declaration("CoordSystemName", "char[100]", "DendroScalar")
    'char CoordSystemName[100];'
    """
    size = array_size(cparam_type)
    base = c_type(cparam_type, scalar_type)
    return f"{base} {cp_name}[{size}];" if size else f"{base} {cp_name};"


def _toml_value(cparam_type: str, default_value: Any) -> Any:
    """
    Render the TOML sample value for a CodeParameter default.

    :param cparam_type: Registered ``cparam_type`` string.
    :param default_value: Registered default value.
    :return: A JSON-serializable value for the sample TOML entry.
    :raises ValueError: If the type has no TOML mapping.
    """
    if cparam_type in ("int",):
        return int(default_value)
    if cparam_type == "bool":
        return bool(default_value)
    if cparam_type in ("REAL", "float", "double", "DendroScalar"):
        return float(default_value)
    raise ValueError(f"No TOML mapping for cparam_type {cparam_type!r}.")


def output_Dendro_parameters_h(solver_stem: str, solver_namespace: str) -> str:
    """
    Emit the generated parameter struct header.

    One member per registered CodeParameter in sorted name order, as BHaH's
    ``BHaH_defines_h`` iterates ``par.glb_code_params_dict``.  No default is
    baked into the struct: defaults live in the registered parameter-defaults
    CFunction and in the sample parameter file.

    :param solver_stem: Lowercase formulation stem for emitted header names.
    :param solver_namespace: Solver namespace, following Dendro's lowercase
        formulation habit (``namespace bssn``).
    :return: The complete C++ header text.
    """
    scalar_type = str(par.parval_from_str("Dendro_scalar_type"))
    lines: List[str] = [BANNER.rstrip("\n"), "#pragma once", ""]
    lines += ["", f'#include "{solver_stem}_types.h"', ""]
    lines.append(f"namespace {solver_namespace}::generated {{")
    lines += ["", "struct GeneratedParams {"]
    emitted = 0
    for cp_name, code_param in sorted(par.glb_code_params_dict.items()):
        if code_param.cparam_type == "#define":
            continue
        lines.append(
            "    " + member_declaration(cp_name, code_param.cparam_type, scalar_type)
        )
        emitted += 1
    lines += ["};  // END STRUCT: GeneratedParams", ""]
    lines.append(f"inline constexpr unsigned NUM_CODE_PARAMETERS = {emitted};")
    lines += ["", f"}}  // END NAMESPACE: {solver_namespace}::generated", ""]
    return "\n".join(lines)


def output_parameter_file_sample() -> str:
    """
    Emit the sample parameter-file section for the runtime parameters.

    Only parameters with ``add_to_parfile`` appear; every value is the
    registered default.

    :return: Parameter-file text with a trailing newline.
    """
    lines: List[str] = ["[params]"]
    for cp_name, code_param in sorted(par.glb_code_params_dict.items()):
        if not code_param.add_to_parfile or code_param.cparam_type == "#define":
            continue
        lines.append(f"{cp_name} = {_format_toml_scalar(code_param)}")
    return "\n".join(lines) + "\n"


def _format_toml_scalar(code_param: Any) -> str:
    """
    Format one parameter-file scalar from a registered CodeParameter.

    :param code_param: The registered CodeParameter.
    :return: The parameter-file literal.
    """
    value = _toml_value(code_param.cparam_type, code_param.defaultvalue)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return repr(value)


