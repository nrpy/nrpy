# nrpy/infrastructures/Dendro/generated_file_banner.py
"""
Emit the provenance banner generated Dendro artifacts carry.

The headers, build files, parameter file and host sources carry it; the
per-CFunction sources do not, matching BHaH, ETLegacy and CarpetX, which banner
their headers, CCL files and parameter files but not per-function sources.

The banner names NRPy, not the generating module.  Naming the module would tie
every emitted byte to a Python file name, so renaming an emitter would rewrite
the generated tree.  ETLegacy and CarpetX already name NRPy without the module
in their own generated banners ("This interface.ccl file was automatically
generated by NRPy"), so this is the established granularity rather than a
third spelling.

Author: Zachariah B. Etienne
        zachetie **at** gmail **dot* com
"""

_LINES = (
    "GENERATED FILE - DO NOT EDIT",
    "AUTOMATICALLY GENERATED BY NRPy",
)


def generated_file_banner(comment: str = "//") -> str:
    """
    Return the provenance banner, one commented line per banner line.

    :param comment: Line-comment token for the emitted language: ``//`` for the
        C++ artifacts, ``#`` for the CMake files and the parameter file.
    :return: The banner, newline-terminated.

    Doctests:
    >>> print(generated_file_banner(), end="")
    // GENERATED FILE - DO NOT EDIT
    // AUTOMATICALLY GENERATED BY NRPy
    >>> print(generated_file_banner("#"), end="")
    # GENERATED FILE - DO NOT EDIT
    # AUTOMATICALLY GENERATED BY NRPy
    """
    return "".join(f"{comment} {line}\n" for line in _LINES)


